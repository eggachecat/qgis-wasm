#!/usr/bin/env bash
# The static-site branch: the built bundle (open-source web layers, no overlay) arranged for GitHub Pages or any file
# server — qgis.wasm / qgis.data only as .gz (GitHub refuses files over 100 MB; loading.js inflates them while they
# stream), coi-serviceworker.js for the COOP/COEP headers a static host cannot send, .nojekyll. Adds one commit on top of the branch.
#
#   scripts/export-pages.sh [branch = github/pages]
# then: GitHub → Settings → Pages → Deploy from a branch → <branch> (root).  Try it locally without any headers:
#   cd <worktree of the branch> && python3 -m http.server 8130  →  http://localhost:8130/
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
BRANCH=${1:-github/pages}
BIN="$ROOT/build/qgis/output/bin"
[ -f "$BIN/qgis.wasm" ] || { echo "no build in $BIN — run scripts/build-qgis.sh first" >&2; exit 1; }
"$ROOT/scripts/stage-web.sh" --oss --compress >/dev/null
SRC=$(git rev-parse --short HEAD)
WT=$(mktemp -d)
trap 'git worktree remove --force "$WT" 2>/dev/null; git branch -D -q "$BRANCH.tmp" 2>/dev/null; true' EXIT
git worktree add --detach -q "$WT" HEAD
(
  cd "$WT"
  git checkout -q --orphan "$BRANCH.tmp"
  git rm -rfq . >/dev/null 2>&1 || true
  find . -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
  # web layers and the module (everything except the big raw files and the .br sidecars)
  rsync -a --exclude 'qgis.wasm' --exclude 'qgis.data' --exclude '*.br' --exclude '*.gz' --exclude '__pycache__' --exclude 'qgis.html' --exclude 'qtlogo.svg' --exclude 'qgisbuildpath.txt' "$BIN/" ./
  for big in qgis.wasm qgis.data; do [ -f "$BIN/$big.gz" ] || { echo "missing $BIN/$big.gz (scripts/compress-bundle.mjs)" >&2; exit 1; }; cp "$BIN/$big.gz" ./; done
  # any other file over GitHub's limit goes as .gz too
  find . -type f -size +95M ! -name '*.gz' | while read -r f; do echo "too big for GitHub, shipping compressed: $f"; gzip -9 "$f"; done
  # the manifest tells loading.js which files exist only compressed
  node -e '
    const fs = require("fs"); const m = JSON.parse(fs.readFileSync("qgis.bundle.json", "utf8"));
    for (const n of Object.keys(m.files || {})) if (fs.existsSync(n + ".gz") && !fs.existsSync(n)) m.files[n].static = "gz";
    m.static = true; fs.writeFileSync("qgis.bundle.json", JSON.stringify(m, null, 2));'
  touch .nojekyll
  node "$ROOT/tests/oss-guard.mjs" . --files   # what is about to be published must be clean (presets, brand, pages)
  cat > README.md <<MD
# QGIS Desktop for WebAssembly — static site

Generated by \`scripts/export-pages.sh\` from commit $SRC: the built bundle arranged for GitHub Pages or any static
file server. \`qgis.wasm\` and \`qgis.data\` are present only as \`.gz\` (inflated in the browser while streaming);
\`coi-serviceworker.js\` supplies the cross-origin isolation headers threads need. Without a server the MCP endpoint,
the CORS proxy and the agent transport are off. Source and documentation: https://github.com/eggachecat/qgis-wasm (branch \`main\`).
MD
  git add -A
  TREE=$(git write-tree)
  PARENT=$(git -C "$ROOT" rev-parse -q --verify "refs/heads/$BRANCH" || true)   # on top of the previous export: pushes stay fast-forward
  NEW=$(GIT_AUTHOR_NAME="${GIT_AUTHOR_NAME:-$(git config user.name || echo export)}" GIT_AUTHOR_EMAIL="${GIT_AUTHOR_EMAIL:-$(git config user.email || echo export@localhost)}" GIT_COMMITTER_NAME="${GIT_AUTHOR_NAME:-$(git config user.name || echo export)}" GIT_COMMITTER_EMAIL="${GIT_AUTHOR_EMAIL:-$(git config user.email || echo export@localhost)}" git commit-tree "$TREE" ${PARENT:+-p "$PARENT"} -m "static site from $SRC")
  git -C "$ROOT" branch -f "$BRANCH" "$NEW"
  git checkout -q --detach "$NEW"
  git branch -D -q "$BRANCH.tmp" 2>/dev/null || true   # (the orphan ref exists only if something was committed on it)
)
echo "branch $BRANCH: $(git rev-parse --short "$BRANCH") ($(git ls-tree -r --name-only "$BRANCH" | wc -l) files, $(du -sh "$BIN" | cut -f1) staged)"
